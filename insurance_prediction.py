def predict_insurance(age, salary):

    customer = np.array([[age, salary]])

    customer_scaled = scaler.transform(customer)

    print("\n====================================")
    print("Customer Details")
    print("Age:", age)
    print("Estimated Salary:", salary)
    print("====================================")

    for name, model in trained_models.items():

        prediction = model.predict(customer_scaled)[0]

        if prediction == 1:
            result = "PURCHASE"
        else:
            result = "NO PURCHASE"

        print(name, ":", result)

